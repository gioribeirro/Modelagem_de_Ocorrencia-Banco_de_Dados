-- V01 C11: inquerito cuja ocorrencia nao esta 'Convertida em inquerito'
SELECT i.id_inquerito FROM INQUERITO i JOIN OCORRENCIA o ON o.id_ocorrencia=i.id_ocorrencia WHERE o.status<>'Convertida em inquérito';
-- V02 C11: ocorrencia 'Convertida em inquerito' sem inquerito
SELECT o.id_ocorrencia FROM OCORRENCIA o LEFT JOIN INQUERITO i ON i.id_ocorrencia=o.id_ocorrencia WHERE o.status='Convertida em inquérito' AND i.id_inquerito IS NULL;
-- V03 C14: ocorrencia registrada por escrivao
SELECT o.id_ocorrencia FROM OCORRENCIA o JOIN SERVIDOR s ON s.id_servidor=o.id_servidor WHERE s.cargo='Escrivão';
-- V04 C14: movimentacao feita por servidor que nao e escrivao nem delegado
SELECT m.id_movimentacao FROM MOVIMENTACAO m JOIN SERVIDOR s ON s.id_servidor=m.id_servidor WHERE s.cargo NOT IN ('Escrivão','Delegado');
-- V05 C11: inquerito sem prova materializada (nenhuma evidencia ate a data de abertura)
SELECT i.id_inquerito FROM INQUERITO i WHERE NOT EXISTS (SELECT 1 FROM EVIDENCIA e WHERE e.id_inquerito=i.id_inquerito AND e.data_apreensao<=i.data_abertura);
-- V06 depoente que nao esta envolvido na ocorrencia do inquerito
SELECT d.id_depoimento FROM DEPOIMENTO d JOIN INQUERITO i ON i.id_inquerito=d.id_inquerito
WHERE NOT EXISTS (SELECT 1 FROM ENVOLVIMENTO e WHERE e.id_ocorrencia=i.id_ocorrencia AND e.id_pessoa=d.id_pessoa);
-- V07 advogado vinculado a envolvido que nao e Acusado
SELECT e.id_pessoa,e.id_ocorrencia FROM ENVOLVIMENTO e WHERE e.id_oab IS NOT NULL AND e.papel<>'Acusado';
-- V08 situacao do inquerito incoerente com data_conclusao
SELECT id_inquerito FROM INQUERITO WHERE (status='Concluído' AND data_conclusao IS NULL) OR (status<>'Concluído' AND data_conclusao IS NOT NULL);
-- V09 inquerito sem movimentacao de instauracao feita por delegado
SELECT i.id_inquerito FROM INQUERITO i WHERE NOT EXISTS (SELECT 1 FROM MOVIMENTACAO m JOIN SERVIDOR s ON s.id_servidor=m.id_servidor WHERE m.id_inquerito=i.id_inquerito AND m.tipo_movimentacao='Instauração' AND s.cargo='Delegado');
-- V10 inquerito aberto antes do registro da ocorrencia
SELECT i.id_inquerito FROM INQUERITO i JOIN OCORRENCIA o ON o.id_ocorrencia=i.id_ocorrencia WHERE i.data_abertura<DATE(o.data_registro);
-- V11 envolvimento com papel 'Advogado' (proibido pela regra R8)
SELECT id_pessoa,id_ocorrencia FROM ENVOLVIMENTO WHERE papel='Advogado';

