-- G01 Indicadores gerais (cartoes do painel)
SELECT COUNT(*) AS total_ocorrencias,
 (SELECT COUNT(*) FROM INQUERITO) AS total_inqueritos,
 ROUND(100.0*(SELECT COUNT(*) FROM INQUERITO)/COUNT(*),1) AS taxa_conversao_pct,
 ROUND(100.0*SUM(canal_registro='Online')/COUNT(*),1) AS pct_online,
 (SELECT COUNT(*) FROM INQUERITO WHERE status='Em investigação') AS inqueritos_em_andamento,
 (SELECT ROUND(AVG(DATEDIFF(data_conclusao,data_abertura)),1) FROM INQUERITO WHERE data_conclusao IS NOT NULL) AS duracao_media_dias
FROM OCORRENCIA;

-- G02 Ocorrencias por mes e variacao sobre o mes anterior (Pergunta 10: volume cresce)
SELECT mes,total,LAG(total) OVER (ORDER BY mes) AS mes_anterior,
 ROUND(100.0*(total-LAG(total) OVER (ORDER BY mes))/LAG(total) OVER (ORDER BY mes),1) AS variacao_pct
FROM (SELECT DATE_FORMAT(data_registro,'%Y-%m') AS mes,COUNT(*) AS total
      FROM OCORRENCIA GROUP BY DATE_FORMAT(data_registro,'%Y-%m')) t
ORDER BY mes;

-- G03 Canal de registro por mes: presencial x online (Pergunta 10)
SELECT DATE_FORMAT(data_registro,'%Y-%m') AS mes,
 SUM(canal_registro='Presencial') AS presencial,
 SUM(canal_registro='Online') AS online,
 ROUND(100.0*SUM(canal_registro='Online')/COUNT(*),1) AS pct_online
FROM OCORRENCIA GROUP BY DATE_FORMAT(data_registro,'%Y-%m') ORDER BY mes;

-- G04 Ranking de naturezas com percentual acumulado (Pareto)
SELECT natureza,total,ROUND(100.0*total/SUM(total) OVER (),1) AS pct,
 ROUND(100.0*SUM(total) OVER (ORDER BY total DESC,natureza ROWS UNBOUNDED PRECEDING)/SUM(total) OVER (),1) AS pct_acumulado
FROM (SELECT n.descricao AS natureza,COUNT(*) AS total
      FROM OCORRENCIA o JOIN NATUREZA_FATO n ON n.id_natureza=o.id_natureza
      GROUP BY n.id_natureza,n.descricao) t
ORDER BY total DESC,natureza;

-- G05 Familia Estelionato (golpe do amor + falsa delegacia + generico) x demais (Pergunta 5)
SELECT CASE WHEN n.descricao LIKE 'Estelionato%' THEN 'Estelionato (todos os tipos)' ELSE n.descricao END AS grupo,
 COUNT(*) AS total,ROUND(100.0*COUNT(*)/(SELECT COUNT(*) FROM OCORRENCIA),1) AS pct
FROM OCORRENCIA o JOIN NATUREZA_FATO n ON n.id_natureza=o.id_natureza
GROUP BY CASE WHEN n.descricao LIKE 'Estelionato%' THEN 'Estelionato (todos os tipos)' ELSE n.descricao END
ORDER BY total DESC;

-- G06 Situacao das ocorrencias (funil de triagem)
SELECT status,COUNT(*) AS total,ROUND(100.0*COUNT(*)/(SELECT COUNT(*) FROM OCORRENCIA),1) AS pct
FROM OCORRENCIA GROUP BY status ORDER BY total DESC;

-- G07 Conversao em inquerito por natureza (Pergunta 11: so com prova materializada)
SELECT n.descricao AS natureza,COUNT(o.id_ocorrencia) AS ocorrencias,COUNT(i.id_inquerito) AS inqueritos,
 ROUND(100.0*COUNT(i.id_inquerito)/COUNT(o.id_ocorrencia),1) AS taxa_conversao_pct
FROM NATUREZA_FATO n
JOIN OCORRENCIA o ON o.id_natureza=n.id_natureza
LEFT JOIN INQUERITO i ON i.id_ocorrencia=o.id_ocorrencia
GROUP BY n.id_natureza,n.descricao ORDER BY taxa_conversao_pct DESC;

-- G08 Prazo medio entre registro da ocorrencia e abertura do inquerito
SELECT ROUND(AVG(DATEDIFF(i.data_abertura,DATE(o.data_registro))),1) AS dias_ate_abertura,
 MIN(DATEDIFF(i.data_abertura,DATE(o.data_registro))) AS minimo,
 MAX(DATEDIFF(i.data_abertura,DATE(o.data_registro))) AS maximo
FROM INQUERITO i JOIN OCORRENCIA o ON o.id_ocorrencia=i.id_ocorrencia;

-- G09 Duracao media dos inqueritos concluidos por prioridade
SELECT prioridade,COUNT(*) AS concluidos,ROUND(AVG(DATEDIFF(data_conclusao,data_abertura)),1) AS duracao_media_dias
FROM INQUERITO WHERE data_conclusao IS NOT NULL GROUP BY prioridade ORDER BY duracao_media_dias DESC;

-- G10 Envelhecimento dos inqueritos em andamento (ref. 2026-10-30)
SELECT CASE WHEN DATEDIFF('2026-10-30',data_abertura)<=30 THEN '0-30 dias'
 WHEN DATEDIFF('2026-10-30',data_abertura)<=60 THEN '31-60 dias'
 WHEN DATEDIFF('2026-10-30',data_abertura)<=90 THEN '61-90 dias'
 ELSE 'mais de 90 dias' END AS faixa,COUNT(*) AS inqueritos
FROM INQUERITO WHERE status='Em investigação'
GROUP BY CASE WHEN DATEDIFF('2026-10-30',data_abertura)<=30 THEN '0-30 dias'
 WHEN DATEDIFF('2026-10-30',data_abertura)<=60 THEN '31-60 dias'
 WHEN DATEDIFF('2026-10-30',data_abertura)<=90 THEN '61-90 dias'
 ELSE 'mais de 90 dias' END
ORDER BY MIN(DATEDIFF('2026-10-30',data_abertura));

-- G11 Carga por delegado: inqueritos instaurados (Pergunta 13). O modelo nao tem FK inquerito->delegado,
-- entao a autoria da instauracao vem de MOVIMENTACAO (tipo 'Instauração').
SELECT p.nome_ficticio AS delegado,COUNT(DISTINCT m.id_inquerito) AS inqueritos_instaurados,
 COUNT(DISTINCT CASE WHEN i.status='Concluído' THEN i.id_inquerito END) AS concluidos
FROM MOVIMENTACAO m
JOIN SERVIDOR s ON s.id_servidor=m.id_servidor
JOIN PESSOA p ON p.id_pessoa=s.id_pessoa
JOIN INQUERITO i ON i.id_inquerito=m.id_inquerito
WHERE s.cargo='Delegado' AND m.tipo_movimentacao='Instauração'
GROUP BY s.id_servidor,p.nome_ficticio ORDER BY inqueritos_instaurados DESC;

-- G12 Carga por escrivao: inqueritos recebidos (distribuicao) e movimentacoes (Pergunta 14: 6 escrivaes)
SELECT p.nome_ficticio AS escrivao,
 COUNT(DISTINCT CASE WHEN m.tipo_movimentacao='Distribuição' THEN m.id_inquerito END) AS inqueritos_recebidos,
 COUNT(*) AS movimentacoes
FROM SERVIDOR s
JOIN PESSOA p ON p.id_pessoa=s.id_pessoa
LEFT JOIN MOVIMENTACAO m ON m.id_servidor=s.id_servidor
WHERE s.cargo='Escrivão'
GROUP BY s.id_servidor,p.nome_ficticio ORDER BY inqueritos_recebidos DESC;

-- G13 Ocorrencias registradas por agente (so agentes registram, escrivao nao: C14)
SELECT p.nome_ficticio AS agente,s.cargo,COUNT(*) AS ocorrencias_registradas
FROM OCORRENCIA o JOIN SERVIDOR s ON s.id_servidor=o.id_servidor JOIN PESSOA p ON p.id_pessoa=s.id_pessoa
GROUP BY s.id_servidor,p.nome_ficticio,s.cargo ORDER BY ocorrencias_registradas DESC;

-- G14 Localidades com mais ocorrencias e natureza predominante
