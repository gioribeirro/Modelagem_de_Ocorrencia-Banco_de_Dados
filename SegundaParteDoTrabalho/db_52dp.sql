 SELECT x.localidade,x.total,x.descricao AS natureza_predominante,
  ROW_NUMBER() OVER (PARTITION BY x.localidade ORDER BY x.qtd DESC,x.descricao) AS rn
 FROM (SELECT o.localidade,n.descricao,COUNT(*) AS qtd,
        SUM(COUNT(*)) OVER (PARTITION BY o.localidade) AS total
       FROM OCORRENCIA o JOIN NATUREZA_FATO n ON n.id_natureza=o.id_natureza
       GROUP BY o.localidade,n.id_natureza,n.descricao) x) y
WHERE rn=1 ORDER BY total DESC;

-- G15 Evidencias por tipo e situacao de custodia
SELECT tipo_evidencia,COUNT(*) AS total,
 SUM(status_custodia='Em análise') AS em_analise,SUM(status_custodia='Sob custódia') AS sob_custodia,
 SUM(status_custodia='Periciada') AS periciada,SUM(status_custodia='Devolvida') AS devolvida
FROM EVIDENCIA GROUP BY tipo_evidencia ORDER BY total DESC;

-- G16 Papeis nas ocorrencias e acusados com advogado vinculado (Pergunta 9)
SELECT papel,COUNT(*) AS total,SUM(id_oab IS NOT NULL) AS com_advogado
FROM ENVOLVIMENTO GROUP BY papel ORDER BY total DESC;

-- G17 Ranking de advogados por acusados vinculados
SELECT a.id_oab,p.nome_ficticio AS advogado,COUNT(*) AS acusados_vinculados
FROM ENVOLVIMENTO e JOIN ADVOGADO a ON a.id_oab=e.id_oab JOIN PESSOA p ON p.id_pessoa=a.id_pessoa
GROUP BY a.id_oab,p.nome_ficticio ORDER BY acusados_vinculados DESC,a.id_oab;

-- G18 Pessoas recorrentes (2 ou mais ocorrencias)
SELECT p.id_pessoa,p.nome_ficticio,COUNT(*) AS ocorrencias,
 SUM(e.papel='Vítima') AS como_vitima,SUM(e.papel='Acusado') AS como_acusado
FROM ENVOLVIMENTO e JOIN PESSOA p ON p.id_pessoa=e.id_pessoa
GROUP BY p.id_pessoa,p.nome_ficticio HAVING COUNT(*)>=2 ORDER BY ocorrencias DESC,p.id_pessoa LIMIT 10;

-- G19 Volume de peças por inquerito (depoimentos, evidencias, movimentacoes)
SELECT ROUND(AVG(d.q),1) AS media_depoimentos,ROUND(AVG(e.q),1) AS media_evidencias,ROUND(AVG(m.q),1) AS media_movimentacoes
FROM INQUERITO i
JOIN (SELECT id_inquerito,COUNT(*) AS q FROM DEPOIMENTO GROUP BY id_inquerito) d ON d.id_inquerito=i.id_inquerito
JOIN (SELECT id_inquerito,COUNT(*) AS q FROM EVIDENCIA GROUP BY id_inquerito) e ON e.id_inquerito=i.id_inquerito
JOIN (SELECT id_inquerito,COUNT(*) AS q FROM MOVIMENTACAO GROUP BY id_inquerito) m ON m.id_inquerito=i.id_inquerito;

