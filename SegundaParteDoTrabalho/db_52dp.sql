CREATE OR REPLACE VIEW vw_bi_ocorrencias AS
SELECT o.id_ocorrencia,DATE(o.data_registro) AS data_registro,DATE_FORMAT(o.data_registro,'%Y-%m') AS ano_mes,
 o.canal_registro,n.descricao AS natureza,
 CASE WHEN n.descricao LIKE 'Estelionato%' THEN 'Estelionato' ELSE n.descricao END AS grupo_natureza,
 n.gravidade,o.localidade,p.nome_ficticio AS agente_registro,o.status AS status_ocorrencia,
 CASE WHEN i.id_inquerito IS NULL THEN 0 ELSE 1 END AS virou_inquerito,
 i.id_inquerito,i.status AS status_inquerito,
 DATEDIFF(i.data_abertura,DATE(o.data_registro)) AS dias_ate_abertura,
 DATEDIFF(i.data_conclusao,i.data_abertura) AS duracao_dias
FROM OCORRENCIA o
JOIN NATUREZA_FATO n ON n.id_natureza=o.id_natureza
LEFT JOIN SERVIDOR s ON s.id_servidor=o.id_servidor
LEFT JOIN PESSOA p ON p.id_pessoa=s.id_pessoa
LEFT JOIN INQUERITO i ON i.id_ocorrencia=o.id_ocorrencia;

CREATE OR REPLACE VIEW vw_bi_inqueritos AS
SELECT i.id_inquerito,i.id_ocorrencia,i.data_abertura,DATE_FORMAT(i.data_abertura,'%Y-%m') AS ano_mes_abertura,
 i.status,i.prioridade,n.descricao AS natureza,
 (SELECT MIN(p.nome_ficticio) FROM MOVIMENTACAO m JOIN SERVIDOR s ON s.id_servidor=m.id_servidor
   JOIN PESSOA p ON p.id_pessoa=s.id_pessoa
  WHERE m.id_inquerito=i.id_inquerito AND m.tipo_movimentacao='Instauração' AND s.cargo='Delegado') AS delegado,
 (SELECT MIN(p.nome_ficticio) FROM MOVIMENTACAO m JOIN SERVIDOR s ON s.id_servidor=m.id_servidor
   JOIN PESSOA p ON p.id_pessoa=s.id_pessoa
  WHERE m.id_inquerito=i.id_inquerito AND m.tipo_movimentacao='Distribuição' AND s.cargo='Escrivão') AS escrivao,
 DATEDIFF(COALESCE(i.data_conclusao,'2026-10-30'),i.data_abertura) AS dias_tramitacao,
 (SELECT COUNT(*) FROM DEPOIMENTO d WHERE d.id_inquerito=i.id_inquerito) AS qtd_depoimentos,
 (SELECT COUNT(*) FROM EVIDENCIA e WHERE e.id_inquerito=i.id_inquerito) AS qtd_evidencias,
 (SELECT COUNT(*) FROM MOVIMENTACAO m WHERE m.id_inquerito=i.id_inquerito) AS qtd_movimentacoes
FROM INQUERITO i
JOIN OCORRENCIA o ON o.id_ocorrencia=i.id_ocorrencia
JOIN NATUREZA_FATO n ON n.id_natureza=o.id_natureza;

CREATE OR REPLACE VIEW vw_bi_kpis_mensais AS
SELECT a.ano_mes,a.ocorrencias,a.presencial,a.online,COALESCE(b.inqueritos_abertos,0) AS inqueritos_abertos
FROM (SELECT DATE_FORMAT(data_registro,'%Y-%m') AS ano_mes,COUNT(*) AS ocorrencias,
       SUM(canal_registro='Presencial') AS presencial,SUM(canal_registro='Online') AS online
      FROM OCORRENCIA GROUP BY DATE_FORMAT(data_registro,'%Y-%m')) a
LEFT JOIN (SELECT DATE_FORMAT(data_abertura,'%Y-%m') AS ano_mes,COUNT(*) AS inqueritos_abertos
      FROM INQUERITO GROUP BY DATE_FORMAT(data_abertura,'%Y-%m')) b ON b.ano_mes=a.ano_mes;

SELECT * FROM vw_bi_kpis_mensais ORDER BY ano_mes;
SELECT * FROM vw_bi_inqueritos ORDER BY id_inquerito LIMIT 10;
SELECT * FROM vw_bi_ocorrencias ORDER BY id_ocorrencia LIMIT 10;

